#!/usr/bin/env python
"""p10_pins.py - write corpus-lab/requirements-portable.txt from the live venv.

Plan E Phase 0.5. The dev venv carries a lot the portable does not need
(fastmcp, lancedb, pytest, keyring). Taking `pip freeze` wholesale would make
the clean-room install slower, larger and -- the part that matters -- would stop
saying which packages the retrieval stack actually depends on.

So this walks the real dependency closure of the four declared roots, using each
installed distribution's own metadata, and pins every package in that closure at
the exact version this venv has. Extras are not followed; an unsatisfiable or
environment-marked requirement is skipped and listed in a trailing comment so
nothing disappears silently.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import labpaths as L  # noqa: E402

import importlib.metadata as md  # noqa: E402

ROOTS = ["fastembed", "onnxruntime", "numpy", "pdfplumber"]
OUT = L.CORPUS_LAB / "requirements-portable.txt"


def _norm(name):
    return name.lower().replace("_", "-").replace(".", "-")


def _requires(dist_name):
    """Direct run-time requirements of an installed distribution."""
    try:
        reqs = md.requires(dist_name) or []
    except md.PackageNotFoundError:
        return [], ["%s: not installed" % dist_name]
    out, skipped = [], []
    for r in reqs:
        # "name (>=1.0) ; extra == 'dev'"  /  "name>=1.0; python_version<'3.9'"
        if ";" in r:
            head, marker = r.split(";", 1)
            if "extra" in marker:
                continue          # extras are not part of the base install
            try:
                from packaging.markers import Marker
                if not Marker(marker.strip()).evaluate():
                    skipped.append("%s (marker not satisfied: %s)"
                                   % (head.strip(), marker.strip()))
                    continue
            except Exception:
                pass
        else:
            head = r
        name = head.strip().split("[")[0]
        for sep in ("(", "<", ">", "=", "!", "~", " "):
            name = name.split(sep)[0]
        name = name.strip()
        if name:
            out.append(name)
    return out, skipped


def main():
    versions = {}
    for d in md.distributions():
        try:
            versions[_norm(d.metadata["Name"])] = d.version
        except Exception:
            continue

    seen, order, skipped, missing = set(), [], [], []
    stack = list(ROOTS)
    while stack:
        name = stack.pop(0)
        key = _norm(name)
        if key in seen:
            continue
        seen.add(key)
        if key not in versions:
            missing.append(name)
            continue
        order.append(key)
        deps, sk = _requires(name)
        skipped.extend(sk)
        stack.extend(deps)

    order.sort()
    lines = [
        "# requirements-portable.txt -- the retrieval stack's runtime closure.",
        "#",
        "# python 3.11.5, claude code 2.1.257",
        "#",
        "# Generated by corpus-lab/bin/p10_pins.py from the lab venv (Plan E Phase",
        "# 0.5). Declared roots: %s." % ", ".join(ROOTS),
        "# Everything below is one of those four or something they require,",
        "# transitively, pinned at the version every number in the report was",
        "# measured with. Dev-only packages (pytest, fastmcp, lancedb, keyring)",
        "# are deliberately absent: the portable does not import them.",
        "#",
        "# Install:  python -m venv .venv && .venv/Scripts/pip install -r requirements-portable.txt",
        "",
    ]
    for key in order:
        lines.append("%s==%s" % (key, versions[key]))

    if missing:
        lines += ["", "# declared but not installed in this venv:"] + \
                 ["#   " + m for m in sorted(set(missing))]
    if skipped:
        lines += ["", "# requirements skipped (environment markers not satisfied here):"] + \
                 ["#   " + s for s in sorted(set(skipped))]

    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote %s with %d pinned packages" % (OUT, len(order)))
    for key in order:
        if key in [_norm(r) for r in ROOTS]:
            print("  root %-14s %s" % (key, versions[key]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
